import { describe, expect, it, vi } from "vitest";
import { ID_SCHEMA } from "@/schemas/id";
import { getMaxMatchesPerUser } from "@/utils/match-limits";
import { analyticsRequestSchema } from "@/server/analytics";
import { ANALYTICS_PAGES } from "@/utils/analytics-events";
import { GET as legacyAvatar } from "@/app/api/player-avatars/v2/route";
import { GET as paletteAvatar } from "@/app/api/player-avatars/v3/route";
import { GET as currentAvatar } from "@/app/api/player-avatars/v4/route";
import { NextRequest } from "next/server";

const request = (query: string) =>
  new NextRequest(`https://example.test/api/avatar?${query}`);

describe("server boundary policies", () => {
  it("accepts only positive PostgreSQL integer identifiers", () => {
    for (const id of [1, 2147483647])
      expect(ID_SCHEMA.safeParse(id).success).toBe(true);
    for (const id of [0, -1, 1.5, 2147483648, NaN, Infinity, "1"])
      expect(ID_SCHEMA.safeParse(id).success).toBe(false);
  });

  it("reads match limits at call time and preserves the default", () => {
    vi.stubEnv("NEXT_PUBLIC_MAX_MATCHES_PER_USER", undefined);
    expect(getMaxMatchesPerUser()).toBe(100);
    vi.stubEnv("NEXT_PUBLIC_MAX_MATCHES_PER_USER", "7");
    expect(getMaxMatchesPerUser()).toBe(7);
    vi.unstubAllEnvs();
  });

  it("accepts public analytics page contracts and rejects arbitrary values", () => {
    const payload = {
      website: "00000000-0000-4000-8000-000000000001",
      hostname: "scalonet.app",
      url: "/",
      title: "Home",
      referrer: "",
    };
    for (const [url, title] of Object.entries(ANALYTICS_PAGES))
      expect(
        analyticsRequestSchema.safeParse({
          type: "event",
          payload: { ...payload, url, title },
        }).success,
      ).toBe(true);
    expect(
      analyticsRequestSchema.safeParse({
        type: "event",
        payload: { ...payload, url: "/private" },
      }).success,
    ).toBe(false);
    expect(
      analyticsRequestSchema.safeParse({
        type: "event",
        payload: { ...payload, title: "Private" },
      }).success,
    ).toBe(false);
  });

  it("preserves avatar version boundaries and immutable SVG responses", async () => {
    const legacy = await legacyAvatar(request("name=Ana")).text();
    expect(
      await legacyAvatar(request("name=Ana&palette=invalid&name=Other")).text(),
    ).toBe(legacy);
    const palette = paletteAvatar(request("name=Ana"));
    const current = currentAvatar(request("name=Ana"));
    expect(palette.headers.get("content-type")).toBe(
      "image/svg+xml; charset=utf-8",
    );
    expect(current.headers.get("cache-control")).toBe(
      "public, max-age=31536000, immutable",
    );
    expect(current.headers.get("x-content-type-options")).toBe("nosniff");
    const svg = await current.text();
    expect(svg).toContain("<svg");
    expect(svg).not.toContain("<metadata");
    expect(svg).not.toContain("<!-- Generated by DiceBear");
    expect(svg).not.toBe(await palette.text());
    expect(svg).not.toBe(legacy);
    for (const get of [paletteAvatar, currentAvatar]) {
      for (const query of [
        "name=",
        "name=Ana&name=Other",
        "name=Ana&palette=invalid",
        `name=${"a".repeat(41)}`,
      ])
        expect(get(request(query)).status).toBe(400);
    }
  });
});
