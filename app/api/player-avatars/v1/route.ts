import { normalizePlayerAvatarName } from "@/utils/player-avatar";
import { Avatar, Style } from "@dicebear/core";
import dylan from "@dicebear/styles/dylan.json";
import { type NextRequest } from "next/server";

const style = new Style(dylan);

// Public, deterministic artwork only. The export browser has no user session.
// This route never reads players, matches or account data.
export function GET(request: NextRequest) {
  const name = request.nextUrl.searchParams.get("name");
  if (!name?.trim() || Array.from(name).length > 40) {
    return new Response("Invalid avatar name", { status: 400 });
  }

  const avatar = new Avatar(style, {
    seed: normalizePlayerAvatarName(name),
    size: 128,
    moodVariant: ["happy", "superHappy"],
    backgroundColor: ["#780000", "#c1121f", "#fdf0d5", "#003049", "#669bbc"],
  });

  // DiceBear retains Dylan's creator, source and CC BY 4.0 license in SVG metadata.
  const attribution =
    "<!-- Adapted/generated by Scaloneta with DiceBear. Dylan! The Avatar Generator by Natalia Spivak, https://www.dylan.graphics/, CC BY 4.0 https://creativecommons.org/licenses/by/4.0/ -->";

  return new Response(attribution + avatar.toString(), {
    headers: {
      "Content-Type": "image/svg+xml; charset=utf-8",
      "Cache-Control": "public, max-age=31536000, immutable",
      "X-Content-Type-Options": "nosniff",
    },
  });
}
