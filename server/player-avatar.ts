import { Avatar, Style, type StyleOptions } from "@dicebear/core";
import thumbs from "@dicebear/styles/thumbs.json";
import { normalizePlayerAvatarName } from "@/utils/player-avatar";
import { getColorPalette, parseColorPalette } from "@/utils/color-palettes";

const style = new Style(thumbs);

export function isValidAvatarName(name: string | null): name is string {
  return !!name?.trim() && Array.from(name).length <= 40;
}

export function playerAvatarResponse(
  name: string,
  options: StyleOptions,
): Response {
  const avatar = new Avatar(style, {
    seed: normalizePlayerAvatarName(name),
    size: 128,
    ...options,
  });
  const svg = avatar
    .toString()
    .replace("<!-- Generated by DiceBear (https://www.dicebear.com) -->", "")
    .replace(/<metadata\b[^>]*>[\s\S]*?<\/metadata>/, "");

  return new Response(svg, {
    headers: {
      "Content-Type": "image/svg+xml; charset=utf-8",
      "Cache-Control": "public, max-age=31536000, immutable",
      "X-Content-Type-Options": "nosniff",
    },
  });
}

export function palettePlayerAvatarResponse(
  params: URLSearchParams,
  options: StyleOptions = {},
): Response {
  const names = params.getAll("name");
  const name = names[0];
  const palette = parseColorPalette(params);
  if (names.length !== 1 || !isValidAvatarName(name) || !palette) {
    return new Response("Invalid avatar name or palette", { status: 400 });
  }
  const colors = getColorPalette(palette).colors;
  return playerAvatarResponse(name, {
    backgroundColor: colors,
    shapeColor: colors,
    ...options,
  });
}
